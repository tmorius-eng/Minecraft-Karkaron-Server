#!/usr/bin/env python3
"""Writes suld-api's PixelFont.java from the pack's 5x7 pixel font (tools/pack/pixelfont.py), so the minimap draws
its coordinates and the area's name in the same letters as the pack's banners. Deterministic.

    python3 -I tools/map/gen_pixel_font.py
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
spec = importlib.util.spec_from_file_location("pixelfont", os.path.join(ROOT, "tools", "pack", "pixelfont.py"))
pf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pf)
OUT = os.path.join(ROOT, "suld-api", "src", "main", "java", "mn", "suld", "api", "map", "PixelFont.java")


# The minimap writes coordinates and place names only; «₮» marks real money in SÜLD (CoinSignTest), so it stays out.
SKIP = {"₮"}


def main() -> None:
    rows = []
    for ch in sorted(pf._G):
        if ch in SKIP:
            continue
        g = pf._G[ch]
        w = len(g[0])
        bits = ", ".join(str(int(r.replace("#", "1").replace(".", "0")[::-1], 2)) for r in g)
        esc = "\\\\" if ch == "\\" else ("\\'" if ch == "'" else ch)
        rows.append(f"        put('{esc}', {w}, {bits});")
    body = "\n".join(rows)
    src = f'''package mn.suld.api.map;

import java.util.HashMap;
import java.util.Map;

/**
 * The pack's 5 x 7 pixel font (Mongolian Cyrillic and Latin capitals, digits, a few signs), for text drawn into map
 * pixels: the minimap's coordinates and the area's name. Generated by tools/map/gen_pixel_font.py from
 * tools/pack/pixelfont.py; do not edit by hand. Lower case is drawn as upper case; a letter the font lacks is skipped.
 */
public final class PixelFont {{

    public static final int HEIGHT = 7, SPACE = {pf.SPACE};

    /** A glyph: its width and one bit mask per row, bit 0 the leftmost pixel. */
    record Glyph(int width, int[] rows) {{
    }}

    private static final Map<Character, Glyph> GLYPHS = new HashMap<>();

    private static void put(char c, int width, int... rows) {{
        GLYPHS.put(c, new Glyph(width, rows));
    }}

    static {{
{body}
    }}

    private PixelFont() {{
    }}

    static Glyph glyph(char c) {{
        Glyph g = GLYPHS.get(c);
        return g != null ? g : GLYPHS.get(Character.toUpperCase(c));
    }}

    /** The width of {{@code text}} in pixels (one pixel between letters). */
    public static int width(String text) {{
        int w = 0;
        for (int i = 0; i < text.length(); i++) {{
            char c = text.charAt(i);
            if (c == ' ') {{
                w += SPACE + 1;
                continue;
            }}
            Glyph g = glyph(c);
            if (g != null) w += g.width() + 1;
        }}
        return Math.max(0, w - 1);
    }}

    /** Draws {{@code text}} into a 128-wide map image with its top-left at (x, y); returns the x after it. */
    public static int draw(byte[] image, int x, int y, String text, byte colour) {{
        for (int i = 0; i < text.length(); i++) {{
            char c = text.charAt(i);
            if (c == ' ') {{
                x += SPACE + 1;
                continue;
            }}
            Glyph g = glyph(c);
            if (g == null) continue;
            for (int r = 0; r < HEIGHT; r++) {{
                for (int b = 0; b < g.width(); b++) {{
                    if ((g.rows()[r] >> b & 1) == 0) continue;
                    int px = x + b, py = y + r;
                    if (px >= 0 && px < 128 && py >= 0 && py < 128) image[py * 128 + px] = colour;
                }}
            }}
            x += g.width() + 1;
        }}
        return x;
    }}
}}
'''
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(src)
    print(f"{len(rows)} glyphs -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
