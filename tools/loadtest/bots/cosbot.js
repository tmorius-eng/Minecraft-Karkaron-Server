const mineflayer = require('mineflayer'); const { execFileSync } = require('child_process');
const ctl = process.argv[2]; const name = 'Cs' + Math.floor(Math.random() * 1000);
const bot = mineflayer.createBot({ host: '127.0.0.1', port: 25571, username: name, version: '1.21.11', auth: 'offline', hideErrors: true });
const sleep = (ms) => new Promise(r => setTimeout(r, ms)); const cmd = (c) => execFileSync(ctl, ['cmd', c]);
const flat = (c) => { if (c == null) return ''; if (typeof c === 'string') return c; const v = c.value || c; let s = ''; if (v.text) s += (v.text.value ?? v.text); const ex = v.extra && (v.extra.value?.value || v.extra.value || v.extra); if (Array.isArray(ex)) ex.forEach(e => s += flat(e.value ? e : { value: e })); return s; };
const log = []; let particles = 0;
bot._client.on('world_particles', () => { particles++; });
bot._client.on('system_chat', (pk) => { const s = flat(pk.content); if (/Урьдчилан|Худалдаж|зүүлээ|хүрэлцэхгүй/.test(s)) log.push(s); });
const title = () => { const w = bot.currentWindow; if (!w) return 'none'; const m = [...JSON.stringify(w.title).matchAll(/"text":\{"type":"string","value":"([^"]*)"/g)].map(x => x[1]).join('|'); return m; };
bot.once('spawn', async () => {
  await sleep(5000); if (bot.currentWindow) await bot.clickWindow(10, 0, 0).catch(() => {});
  await sleep(2500); if (bot.currentWindow) bot.closeWindow(bot.currentWindow);
  cmd('suld coins ' + name + ' 5000'); await sleep(800);
  bot.chat('/cosmetics'); await sleep(1500); log.push('GRID title: ' + title().replace(/[^\u0000-￿]/g, '?').slice(0, 80));
  bot.clickWindow(29, 0, 0); await sleep(1500); log.push('CATEGORY title: ' + title().slice(-40));
  const w = bot.currentWindow; log.push('items: ' + w.slots.slice(0, 9).map(s => s && s.name).join(','));
  particles = 0; await bot.clickWindow(0, 0, 1 /* shift-click */); await sleep(2500); log.push('preview particles: ' + particles);
  await bot.clickWindow(0, 0, 0); await sleep(1500);
  log.push('after buy: ' + (bot.currentWindow && bot.currentWindow.slots[0] && JSON.stringify(bot.currentWindow.slots[0].customName).includes('Талын') ? 'slot0 is Талын Салхи' : '?'));
  if (bot.currentWindow) bot.closeWindow(bot.currentWindow);
  await sleep(500); particles = 0; await sleep(3000); log.push('aura particles in 3s while equipped: ' + particles);
  console.log(log.join('\n')); bot.quit(); process.exit(0);
});
setTimeout(() => { console.log(log.join('\n')); process.exit(1); }, 60000);
