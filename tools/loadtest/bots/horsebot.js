const mineflayer = require('mineflayer'); const { execFileSync } = require('child_process');
const ctl = process.argv[2]; const name = 'Hb' + Math.floor(Math.random() * 1000);
const bot = mineflayer.createBot({ host: '127.0.0.1', port: 25571, username: name, version: '1.21.11', auth: 'offline', hideErrors: true });
const sleep = (ms) => new Promise(r => setTimeout(r, ms)); const cmd = (c) => execFileSync(ctl, ['cmd', c]);
const flat = (c) => { if (c == null) return ''; if (typeof c === 'string') return c; const v = c.value || c; let s = ''; if (v.text) s += (v.text.value ?? v.text); const ex = v.extra && (v.extra.value?.value || v.extra.value || v.extra); if (Array.isArray(ex)) ex.forEach(e => s += flat(e.value ? e : { value: e })); return s; };
const log = [];
bot._client.on('system_chat', (pk) => { const s = flat(pk.content); if (/морь|Морь|мори/i.test(s)) log.push((pk.overlay ? 'BAR ' : '') + s); });
const horses = () => Object.values(bot.entities).filter(e => e.name === 'horse').length;
bot.once('spawn', async () => {
  await sleep(5000);
  if (bot.currentWindow) await bot.clickWindow(10, 0, 0).catch(() => {});
  await sleep(2000);
  bot.chat('/mori'); await sleep(1500); log.push('lvl1 horses=' + horses() + ' vehicle=' + !!bot.vehicle);
  cmd('suld exp ' + name + ' 5000'); await sleep(1000);
  bot.chat('/mori'); await sleep(2000); log.push('lvl ok horses=' + horses() + ' vehicle=' + !!bot.vehicle);
  cmd('ride ' + name + ' dismount'); await sleep(2500); log.push('after dismount horses=' + horses() + ' vehicle=' + !!bot.vehicle);
  await sleep(4000); bot.chat('/mori'); await sleep(2000); log.push('again horses=' + horses() + ' vehicle=' + !!bot.vehicle);
  bot.chat('/mori'); await sleep(1500); log.push('toggle off horses=' + horses());
  console.log(log.join('\n')); bot.quit(); process.exit(0);
});
setTimeout(() => { console.log(log.join('\n')); process.exit(0); }, 60000);
