SPACE = 3


def _bold(g: list[str]) -> list[str]:
    """Bold weight: double the outer columns (the stems) and keep the inner gaps, so И, М, Ж stay readable."""
    n = len(g[0])
    cols = [0, 0] if n == 1 else [0, 0] + list(range(1, n - 1)) + [n - 1, n - 1]
    return ["".join(row[c] for c in cols) for row in g]


def glyph(ch: str, bold: bool) -> list[str]:
    g = _G[ch]
    return _bold(g) if bold else g


def text_width(text: str, bold: bool = False) -> int:
    w = 0
    for ch in text.upper():
        w += (SPACE + (1 if bold else 0)) if ch == " " else len(glyph(ch, bold)[0])
        w += 1
    return max(0, w - 1)


def draw_text(img: Image.Image, x: int, y: int, text: str, color, shadow=None, bold: bool = False) -> None:
    """Draw text with its top-left at (x, y); optional 1 px drop shadow (down-right); bold = heavy stems."""
    px = img.load()
    for pass_ in ("shadow", "ink") if shadow else ("ink",):
        cx = x + (1 if pass_ == "shadow" else 0)
        cy = y + (1 if pass_ == "shadow" else 0)
        col = shadow if pass_ == "shadow" else color
        for ch in text.upper():
            if ch == " ":
                cx += SPACE + 1 + (1 if bold else 0)
                continue
            g = glyph(ch, bold)
            for gy, row in enumerate(g):
                for gx, c in enumerate(row):
                    if c == "#":
                        X, Y = cx + gx, cy + gy
                        if 0 <= X < img.width and 0 <= Y < img.height:
                            px[X, Y] = tuple(col) + ((255,) if len(col) == 3 else ())
            cx += len(g[0]) + 1


def badge(text: str, fill, edge, ink=(255, 255, 255), shadow=None) -> Image.Image:
    """A rounded pill with the label, 9 px tall (for TAB / chat rank badges)."""
    w = text_width(text) + 6
    img = Image.new("RGBA", (w, 9), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rectangle([1, 0, w - 2, 8], fill=tuple(fill) + (255,))
    d.rectangle([0, 1, w - 1, 7], fill=tuple(fill) + (255,))
    for x in range(1, w - 1):
        img.putpixel((x, 0), tuple(edge) + (255,))
        img.putpixel((x, 8), tuple(edge) + (255,))
    for y in range(1, 8):
        img.putpixel((0, y), tuple(edge) + (255,))
        img.putpixel((w - 1, y), tuple(edge) + (255,))
    draw_text(img, 3, 1, text, ink, shadow)
    return img
